import { BOOKS } from "./books.ts";
import { compareRefs, label, parseRefs, type Ref } from "./parse.ts";

export type Page = {
  path: string;
  content: string;
  navTitle?: string; // title from SUMMARY.md, used when the page has no "# " heading
};

export type BuildOptions = {
  outputPath: string; // vault path of the index page, e.g. "Theologicus/scripture-index.md"
  title: string;
  headerImage: string; // src for <img class="intro-right">, relative to the index page; "" = none
  includeChapters: boolean;
  coverageOnIndex?: boolean; // append a coverage section to the index page
};

export type BuildResult = {
  markdown: string; // the index page
  coverage: string; // standalone coverage report
  refs: number;
  passages: number;
  pages: number;
  chaptersCited: number;
  chaptersTotal: number;
};

const NT_START = BOOKS.findIndex((b) => b.name === "Matthew");

/** Paths listed in mdBook's SUMMARY.md (relative to the book folder), in book order. */
export function summaryOrder(summary: string): string[] {
  return [...summary.matchAll(/\]\(([^)\s]+\.md)\)/g)].map((m) => decodeURI(m[1]).replace(/^\.\//, ""));
}

/** Link text of each page in SUMMARY.md, keyed by path relative to the book folder. */
export function summaryTitles(summary: string): Map<string, string> {
  return new Map(
    [...summary.matchAll(/\[([^\]]+)\]\(([^)\s]+\.md)\)/g)].map((m) => [decodeURI(m[2]).replace(/^\.\//, ""), m[1]]),
  );
}

/** Page title: first "# " heading, else its SUMMARY.md title (pages styled with an HTML title), else the filename. */
export function pageTitle(md: string, path: string, navTitle?: string): string {
  const body = md.replace(/^(```|~~~)[^\n]*\n[\s\S]*?^\1[^\n]*$/gm, "");
  const h1 = /^#[ \t]+(.+?)[ \t#]*$/m.exec(body)?.[1];
  const raw = h1 ?? (navTitle?.trim() || path.split("/").pop()!.replace(/\.md$/, ""));
  return raw
    .replace(/<[^>]+>/g, "")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/[*_`]/g, "")
    .replace(/\s+/g, " ")
    .replace(/([[\]])/g, "\\$1")
    .trim();
}

/** Relative link from one vault file to another, URL-encoded for Markdown. */
export function relLink(from: string, to: string): string {
  const a = from.split("/").slice(0, -1);
  const b = to.split("/");
  let i = 0;
  while (i < a.length && i < b.length - 1 && a[i] === b[i]) i++;
  const parts = [...Array(a.length - i).fill(".."), ...b.slice(i)];
  return parts.map((p) => (p === ".." ? p : encodeURIComponent(p).replace(/\(/g, "%28").replace(/\)/g, "%29"))).join("/");
}

/** mdBook's heading id: lowercase, punctuation dropped, spaces to dashes. */
const anchor = (s: string) => s.toLowerCase().replace(/[^a-z0-9 _-]/g, "").trim().replace(/ /g, "-");

export function buildIndex(pages: Page[], order: string[] | null, opt: BuildOptions): BuildResult {
  const rank = new Map((order ?? []).map((p, i) => [p, i]));
  const sorted = [...pages].sort(
    (x, y) => (rank.get(x.path) ?? Infinity) - (rank.get(y.path) ?? Infinity) || x.path.localeCompare(y.path),
  );

  // passage key -> { ref, page paths in book order }
  const passages = new Map<string, { ref: Ref; pages: Set<string> }>();
  const titles = new Map<string, string>();
  // Chapter coverage counts every reference, including whole chapters left out of the index.
  const hits = BOOKS.map((b) => new Array<number>(b.chapters + 1).fill(0));
  const bookPages = BOOKS.map(() => new Set<string>());
  let refs = 0;
  for (const page of sorted) {
    let found = false;
    for (const ref of parseRefs(page.content)) {
      for (let c = ref.c1; c <= ref.c2; c++) hits[ref.book][c]++;
      bookPages[ref.book].add(page.path);
      if (!opt.includeChapters && ref.v1 === undefined) continue;
      const key = `${ref.book} ${label(ref)}`;
      const entry = passages.get(key) ?? { ref, pages: new Set<string>() };
      entry.pages.add(page.path);
      passages.set(key, entry);
      refs++;
      found = true;
    }
    if (found) titles.set(page.path, pageTitle(page.content, page.path, page.navTitle));
  }

  const byBook = new Map<number, { ref: Ref; pages: Set<string> }[]>();
  for (const e of [...passages.values()].sort((x, y) => compareRefs(x.ref, y.ref))) {
    const list = byBook.get(e.ref.book) ?? [];
    list.push(e);
    byBook.set(e.ref.book, list);
  }

  const nav = (from: number, to: number) =>
    [...byBook.keys()]
      .filter((b) => b >= from && b < to)
      .map((b) => `[${BOOKS[b].name}](#${anchor(BOOKS[b].name)})`)
      .join(" · ");

  const out: string[] = [];
  if (opt.headerImage) out.push(`<img class="intro-right" src="${opt.headerImage}">`, "");
  out.push(
    `# ${opt.title}`,
    "",
    "<!-- Generated by the Scripture Index plugin. Edits to this page are overwritten. -->",
    "",
    "Every passage of Scripture cited in this book, in canonical order, with the pages that cite it.",
    "",
  );
  const ot = nav(0, NT_START);
  const nt = nav(NT_START, BOOKS.length);
  if (ot) out.push(`**Old Testament:** ${ot}`, "");
  if (nt) out.push(`**New Testament:** ${nt}`, "");

  for (const [b, entries] of byBook) {
    out.push(`## ${BOOKS[b].name}`, "");
    for (const e of entries) {
      const links = [...e.pages].map((p) => `[${titles.get(p)}](${relLink(opt.outputPath, p)})`);
      out.push(`- **${BOOKS[b].name} ${label(e.ref)}** — ${links.join(" · ")}`);
    }
    out.push("");
  }

  const cov = coverage(hits, bookPages);
  if (opt.coverageOnIndex) out.push(...renderCoverage(cov, 2), "");

  return {
    markdown: out.join("\n"),
    coverage: [
      "# Scripture Coverage",
      "",
      "<!-- Generated by the Scripture Index plugin. Edits to this page are overwritten. -->",
      "",
      ...renderCoverage(cov, 1),
      "",
    ].join("\n"),
    refs,
    passages: passages.size,
    pages: titles.size,
    chaptersCited: cov.reduce((a, r) => a + r.cited, 0),
    chaptersTotal: cov.reduce((a, r) => a + r.chapters, 0),
  };
}

type BookCoverage = { book: number; chapters: number; cited: number; uncited: number[]; pages: number };

function coverage(hits: number[][], bookPages: Set<string>[]): BookCoverage[] {
  return BOOKS.map((b, i) => {
    const uncited: number[] = [];
    for (let c = 1; c <= b.chapters; c++) if (!hits[i][c]) uncited.push(c);
    return { book: i, chapters: b.chapters, cited: b.chapters - uncited.length, uncited, pages: bookPages[i].size };
  });
}

/** [1,2,3,5,7,8] -> "1–3, 5, 7–8" */
export function chapterRanges(cs: number[]): string {
  const out: string[] = [];
  for (let i = 0; i < cs.length; ) {
    let j = i;
    while (j + 1 < cs.length && cs[j + 1] === cs[j] + 1) j++;
    out.push(i === j ? `${cs[i]}` : `${cs[i]}\u2013${cs[j]}`);
    i = j + 1;
  }
  return out.join(", ");
}

const pct = (r: BookCoverage) => Math.round((100 * r.cited) / r.chapters);
const bar = (r: BookCoverage) => {
  const n = Math.round((10 * r.cited) / r.chapters);
  return "\u2593".repeat(n) + "\u2591".repeat(10 - n);
};

/** Coverage section. `level` = heading level of the section title (1 = page title already given). */
function renderCoverage(cov: BookCoverage[], level: number): string[] {
  const h = (k: number) => "#".repeat(Math.min(level + k, 6));
  const cited = cov.reduce((a, r) => a + r.cited, 0);
  const total = cov.reduce((a, r) => a + r.chapters, 0);
  const out: string[] = [];
  if (level > 1) out.push(`${h(0)} Coverage`, "");
  out.push(
    `**${cited.toLocaleString("en-US")} of ${total.toLocaleString("en-US")} chapters (${Math.round((100 * cited) / total)}%)** are cited at least once. A chapter counts as cited if any reference touches it, even a single verse.`,
    "",
  );

  const never = cov.filter((r) => r.cited === 0);
  if (never.length) out.push(`${h(1)} Never cited`, "", never.map((r) => BOOKS[r.book].name).join(" · "), "");

  const partial = cov.filter((r) => r.cited > 0 && r.cited < r.chapters).sort((a, b) => pct(a) - pct(b) || a.book - b.book);
  if (partial.length) {
    out.push(`${h(1)} Least covered`, "", "| Book | Cited | Uncited chapters |", "| --- | --- | --- |");
    for (const r of partial.slice(0, 10))
      out.push(`| ${BOOKS[r.book].name} | ${r.cited}/${r.chapters} (${pct(r)}%) | ${chapterRanges(r.uncited)} |`);
    out.push("");
  }

  out.push(`${h(1)} By book`, "");
  for (const [name, from, to] of [["Old Testament", 0, NT_START], ["New Testament", NT_START, BOOKS.length]] as const) {
    out.push(`${h(2)} ${name}`, "", "| Book | Coverage | Cited | Pages | Uncited chapters |", "| --- | --- | --- | --- | --- |");
    for (const r of cov.slice(from, to))
      out.push(
        `| ${BOOKS[r.book].name} | ${bar(r)} | ${r.cited}/${r.chapters} | ${r.pages} | ${r.uncited.length === 0 ? "\u2713 all" : r.cited === 0 ? "all" : chapterRanges(r.uncited)} |`,
      );
    out.push("");
  }
  return out;
}
